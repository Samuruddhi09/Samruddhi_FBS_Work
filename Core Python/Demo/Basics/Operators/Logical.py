# 1. and: if both operands are True then return True otherwise Flase
print ('and operator')
print(True and True)
print(True and False)
print(False and True)
print(False and False)

# 2. or: if both operands are False then return False otherwise True
print ('or operator')
print(True or True)
print(True or False)
print(False or True)
print(False or False)

# 3. not: Opposite of operand 
print ('not operator')
print (not True)
print (not False)